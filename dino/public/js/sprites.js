const FIXED = { o: '#ffffff', k: '#333333', y: '#ffd23f', r: '#e5533d', g: '#c9c9c9' };
const cache = new Map();

export function getSprite(name, color = '#535353') {
  const key = name + color;
  let c = cache.get(key);
  if (c) return c;
  const rows = SPRITES[name];
  const w = Math.max(...rows.map((r) => r.length));
  c = document.createElement('canvas');
  c.width = w;
  c.height = rows.length;
  const ctx = c.getContext('2d');
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      if (ch === '.') continue;
      ctx.fillStyle = ch === '#' ? color : FIXED[ch] || color;
      ctx.fillRect(x, y, 1, 1);
    }
  });
  cache.set(key, c);
  return c;
}

// (x, y) は左上。flip で左右反転
export function drawSprite(ctx, name, color, x, y, scale = 2, flip = false) {
  const s = getSprite(name, color);
  if (!flip) {
    ctx.drawImage(s, Math.round(x), Math.round(y), s.width * scale, s.height * scale);
    return;
  }
  ctx.save();
  ctx.translate(Math.round(x) + s.width * scale, Math.round(y));
  ctx.scale(-1, 1);
  ctx.drawImage(s, 0, 0, s.width * scale, s.height * scale);
  ctx.restore();
}

export function spriteSize(name, scale = 2) {
  const rows = SPRITES[name];
  return { w: Math.max(...rows.map((r) => r.length)) * scale, h: rows.length * scale };
}
